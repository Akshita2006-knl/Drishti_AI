import os
import shutil
import torch
import tkinter as tk
from tkinter import filedialog  
from PIL import Image
from transformers import CLIPProcessor, CLIPModel

def run_interactive_desktop_pipeline():
    print("\n" + "="*70)
    print("👁️ INTERACTIVE DIGITAL RETINOPATHY ENGINE IS ONLINE")
    print("="*70)
    
    tuned_model_path = "./idrid_tuned_model"
    
    # 1. Validation Check for Custom Model Files
    if not os.path.exists(tuned_model_path):
        print(f"[ERROR] Fine-tuned model directory not found at '{tuned_model_path}'!")
        print("👉 Action Required: Unzip 'model.zip' and move the 'idrid_tuned_model' folder here.")
        return
        
    # 2. POP OPEN NATIVE WINDOWS FILE EXPLORER DIALOG
    print("[PROMPT] Opening Windows File Browser dialog box... Please select an eye scan image.")
    
    root = tk.Tk()
    root.withdraw() 
    root.attributes('-topmost', True) 
    
    selected_file = filedialog.askopenfilename(
        title="Select Retinal Fundus Image Scan",
        filetypes=[("Image Files", "*.jpg *.jpeg *.png")]
    )
    
    root.destroy() 
    
    if not selected_file:
        print("[CANCELLED] User closed the window without picking an image file.")
        return
        
    print(f"[SUCCESS] Loaded file profile: {selected_file}")
    
    # 3. OVERWRITE THE RAW FILE PATH TO FEED THE MATLAB ENGINE
    target_input_folder = "input_images"
    os.makedirs(target_input_folder, exist_ok=True)
    fixed_matlab_input_path = os.path.join(target_input_folder, "sample_eye.jpg")
    
    shutil.copy2(selected_file, fixed_matlab_input_path)
    print("[INFO] Saved temporary raw image stream to disk space.")
    print("👉 Action Required: Open MATLAB and click 'Run' on 'preprocess.m' now to filter this scan!")
    
    # Pause execution loop block to give user time to execute the MATLAB script run
    input("\n[PAUSE] Once you have run the MATLAB preprocess script, press ENTER here to calculate diagnostics...")
    
    # 4. Check for the Preprocessed Image Matrix generated by MATLAB
    processed_image_path = os.path.join("processed_images", "cleaned_eye.png")
    if not os.path.exists(processed_image_path):
        print(f"\n[ERROR] Processed image target '{processed_image_path}' could not be located!")
        print("👉 Make sure you ran the MATLAB script before pressing enter.")
        return

    # Ingest the fine-tuned weights configuration setup
    print("\n[INFO] Loading Local Fine-Tuned IDRiD Weights Portfolio...")
    try:
        model = CLIPModel.from_pretrained(tuned_model_path)
        processor = CLIPProcessor.from_pretrained(tuned_model_path)
    except Exception as e:
        print(f"[ERROR] Failed to read local model configuration files. Details: {e}")
        return

    image = Image.open(processed_image_path).convert("RGB")
    
    # Standard international screening classification boundaries
    labels = [
        "A normal retinal fundus with no signs of diabetic retinopathy",
        "Mild non-proliferative diabetic retinopathy showing minor microaneurysms",
        "Moderate diabetic retinopathy with noticeable exudates and hemorrhages",
        "Severe retinopathy with multiple cotton wool spots and bleeding",
        "Proliferative diabetic retinopathy with advanced neovascularization"
    ]
    
    print("[INFO] Aligning spatial image tokens with clinical criteria text matrices...")
    inputs = processor(text=labels, images=image, return_tensors="pt", padding=True)
    
    # 5. Execute Diagnostic Evaluation Session
    with torch.no_grad():
        outputs = model(**inputs)
        
    logits_per_image = outputs.logits_per_image 
    
    # FIXED: Extract the raw 1D array row index vector to separate individual float values
    probabilities = logits_per_image.softmax(dim=-1).cpu().numpy()[0]
        
    # 6. Print out the Final Integrated Screening Report Grid
    print("\n" + "="*70)
    print("             CLINICAL DIAGNOSTIC SCREEN REPORT           ")
    print("="*70)
    for label, prob in zip(labels, probabilities):
        # Now correctly parses as an individual floating-point value scalar entry
        print(f"[{prob:6.2%}] Match Confidence -> {label}")
    print("="*70)
    
    best_match_idx = probabilities.argmax()
    print(f"\n🥇 FINAL EVALUATION SELECTION:")
    print(f"👉 {labels[best_match_idx]} (Confidence Score: {probabilities[best_match_idx]:.2%})\n")

if __name__ == "__main__":
    run_interactive_desktop_pipeline()
